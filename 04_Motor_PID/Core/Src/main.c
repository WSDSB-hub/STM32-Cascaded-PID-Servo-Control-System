  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_2, GPIO_PIN_RESET); // AIN2 = 低
  __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, 200);    // 初始占空比 20%

