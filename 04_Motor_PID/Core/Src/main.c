// PID 参数与变量
volatile float Kp = 4.5f;
volatile float Ki = 0.45f;
volatile float Kd = 0.15f;
volatile float target_rpm = 160.0f;
volatile float current_rpm = 0.0f;
volatile float pid_output = 0.0f;

// PID 内部状态
static float integral = 0.0f;
static float last_error = 0.0f;
static float prev_error = 0.0f;

// 编码器每圈脉冲数（电机轴）
#define PULSES_PER_REV 836.0f

// 位置式 PID 计算（速度环）
void Motor_PID_Calc(void)
{
    float error = target_rpm - current_rpm;
    integral += error;
    if (integral > 500.0f) integral = 500.0f;
    if (integral < -100.0f) integral = -100.0f;

    float output = 650.0f;   // 基础占空比 65%
    output += Kp * error;
    output += Ki * integral;
    output += Kd * (error - 2.0f * last_error + prev_error);

    if (output > 900.0f) output = 900.0f;
    if (output < 50.0f)  output = 50.0f;

    pid_output = output;
    prev_error = last_error;
    last_error = error;
}

